import { MCQItem } from '../types/constitution';

interface RawMCQ {
  qNum: number;
  sec: string;
  q: string;
  a: string;
  b: string;
  c: string;
  d: string;
  ans: 'a' | 'b' | 'c' | 'd';
}

function buildMcqs(topicId: string, rawList: RawMCQ[]): MCQItem[] {
  return rawList.map((item) => {
    const correctText = item[item.ans];
    return {
      id: `mcq-${topicId.replace(/\s|&/g, '_')}-${item.qNum}`,
      topicId,
      partNumber: 3,
      questionNumber: item.qNum,
      fromSection: item.sec,
      question: item.q,
      options: [
        { key: 'a', text: item.a },
        { key: 'b', text: item.b },
        { key: 'c', text: item.c },
        { key: 'd', text: item.d },
      ],
      correctOption: item.ans,
      explanation: `Correct Answer: (${item.ans}) ${correctText} — Verified from Unit 1 Part 3 Study Text (${item.sec}).`,
    };
  });
}

